/**
 * build:apps-script — bundle slackline's Apps Script adapter into one
 * script for a Google Apps Script project (which has no module system).
 *
 *   slackline build:apps-script                # → ./slackline.js
 *   slackline build:apps-script --out gas/slackline.js
 *
 * The output defines a global `Slackline` with createAppsScriptApp, route,
 * message/view/options builders, UserError and createGasClient. Push it
 * next to your Code.js with clasp.
 */

import { parseArgs } from 'node:util';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { bundle } from '../bundle.js';

const LIB_ROOT = fileURLToPath(new URL('../../', import.meta.url));

export async function buildAppsScript() {
  const pkg = JSON.parse(await readFile(resolve(LIB_ROOT, '../package.json'), 'utf8'));
  return bundle({
    entry: resolve(LIB_ROOT, 'apps-script.js'),
    root: LIB_ROOT,
    globalName: 'Slackline',
    banner: `/**\n * ${pkg.name} ${pkg.version} — Google Apps Script bundle.\n`
      + ' * Generated by `slackline build:apps-script`; do not edit — rebuild instead.\n */\n',
  });
}

export async function run(argv, { stdout }) {
  const { values } = parseArgs({
    args: argv,
    options: { out: { type: 'string', default: 'slackline.js' } },
  });
  const out = resolve(values.out);
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, await buildAppsScript());
  stdout.write(`Wrote Apps Script bundle to ${out}\n`);
  return 0;
}
